std::optional<std::string_view> emojiForShortcode(std::string_view name) {
  if (name.empty() || name.size() > kMaximumEmojiShortcodeBytes) return std::nullopt;
  const auto found = std::lower_bound(std::begin(kEmoji), std::end(kEmoji), name,
                                      [](const EmojiEntry& entry, std::string_view key) { return entry.name < key; });
  if (found == std::end(kEmoji) || found->name != name) return std::nullopt;
  return found->emoji;
}

std::size_t emojiShortcodeCount() { return std::size(kEmoji); }

