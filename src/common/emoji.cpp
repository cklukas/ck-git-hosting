constexpr bool sortedAndUnique() {
  for (std::size_t index = 1; index < std::size(kEmoji); ++index) {
    if (!(kEmoji[index - 1].name < kEmoji[index].name)) return false;
  }
  return true;
}
static_assert(sortedAndUnique(), "kEmoji must be sorted by name without duplicates");

constexpr bool namesFit() {
  for (const auto& entry : kEmoji) {
    if (entry.name.empty() || entry.name.size() > kMaximumEmojiShortcodeBytes) return false;
  }
  return true;
}
static_assert(namesFit(), "an emoji shortcode is empty or longer than kMaximumEmojiShortcodeBytes");

